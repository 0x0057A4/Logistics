import test from 'node:test';
import assert from 'node:assert/strict';
import {Simulation} from '../dist/core.js';
import {boot,makeLocks} from './ui-harness.js';
const key='industrie-logistik-v1-guided';
test('Gesperrter Storage-Getter: Start bleibt sicher; expliziter temporärer Betrieb funktioniert',async()=>{
 const ui=await boot({storageGetterError:true});
 assert.equal(ui.run('writable'),false);assert.equal(ui.run('temporary'),false);
 assert.equal(await ui.click('start'),false);
 ui.click('temporary');assert.equal(ui.run('temporary'),false);await ui.click('confirmOk');
 assert.equal(ui.run('temporary'),true);ui.click('starter');
 assert.ok(ui.run('sim.state.buildings.length')>0);
 ui.run('setSpeed(4)');assert.equal(ui.run('speed'),4);
 ui.click('save');ui.run('render(true)');
 assert.equal(ui.nodes.get('#storageWarning').hidden,false);
 assert.match(ui.nodes.get('#statusText').textContent,/NICHT GESPEICHERT/);
 assert.doesNotMatch(ui.nodes.get('#toast').textContent,/gesichert/i);
 assert.equal(ui.memory.size,0);
});
test('Volles Storage: Daten bleiben erhalten; JSON und Retry verfügbar; keine stille Flüchtigkeit',async()=>{
 const memory=new Map([[key,new Simulation().serialize()]]);
 let blocked=true;
 const storage={getItem:k=>memory.get(k)||null,setItem(k,v){if(blocked)throw new DOMException('Full','QuotaExceededError');memory.set(k,v);},removeItem:k=>memory.delete(k)};
 const ui=await boot({memory,storage});const saved=memory.get(key);
 assert.equal(ui.run('writable'),false);assert.equal(ui.run('temporary'),false);
 assert.equal(memory.get(key),saved);ui.click('export');
 blocked=false;await ui.click('retryStorage');assert.equal(ui.run('writable'),true);
 ui.click('starter');blocked=true;ui.click('save');
 assert.equal(ui.run('temporary'),false);assert.equal(ui.run('dirty'),true);
 assert.equal(memory.get(key),saved);assert.match(ui.nodes.get('#statusText').textContent,/NICHT GESPEICHERT/);
 blocked=false;await ui.click('retryStorage');await ui.click('confirmOk');
 assert.equal(ui.run('dirty'),false);assert.match(ui.nodes.get('#statusText').textContent,/Gesichert/);
 ui.run('guard.dispose()');
});
test('Temporärer Import und Neustart schreiben keine bestehenden Modi; normaler Tab bleibt geschützt',async()=>{
 const memory=new Map(),locks=makeLocks();
 const first=await boot({memory,locks});await first.click('start');first.click('starter');first.click('save');
 const saved=memory.get(key),second=await boot({memory,locks});
 second.click('temporary');await second.click('confirmOk');second.click('starter');
 assert.equal(memory.get(key),saved);assert.equal(first.run('guard.owns(sim.state.mode)'),true);
 const candidate=new Simulation({mode:'sandbox'});candidate.command({type:'hire',role:'production'});const raw=candidate.serialize();
 await second.nodes.get('#importFile').onchange({target:{files:[{size:raw.length,text:async()=>raw}],value:''}});
 await second.click('confirmOk');assert.equal(second.run('sim.state.mode'),'sandbox');
 assert.equal(second.run('sim.state.workers.length'),1);assert.equal(memory.has('industrie-logistik-v1-sandbox'),false);
 assert.equal(await second.submit('loadMode',{mode:'guided'}),false);assert.equal(second.run('sim.state.mode'),'sandbox');
 second.click('start');await second.click('confirmOk');
 assert.equal(second.run('sim.state.mode'),'guided');assert.equal(memory.get(key),saved);
 assert.equal(second.nodes.get('#storageWarning').hidden,false);first.run('guard.dispose()');
});
test('Retry nach Lockverlust: Abbruch verhindert Autosave und Mutation; konkurrierender Tab bleibt geschützt',async()=>{
 const memory=new Map(),locks=makeLocks(),a=await boot({memory,locks});
 await a.click('start');a.click('starter');const unsaved=a.run('sim.serialize()');
 a.run('guard.release();writable=false');
 await new Promise(resolve=>setImmediate(resolve));
 const b=await boot({memory,locks});b.submit('hire',{role:'production'});b.click('save');
 const latest=memory.get(key);b.run('guard.release();writable=false');
 await new Promise(resolve=>setImmediate(resolve));
 await a.click('retryStorage');
 assert.equal(a.run('writable'),false);assert.equal(a.run('guard.owns(sim.state.mode)'),false);
 a.click('save');assert.equal(memory.get(key),latest);
 a.click('confirmCancel');a.click('starter');a.run('save();setSpeed(4)');
 assert.equal(a.run('sim.serialize()'),unsaved);assert.equal(a.run('speed'),0);assert.equal(memory.get(key),latest);
 await a.click('retryStorage');
 await new Promise(resolve=>setImmediate(resolve));
 await b.click('retryStorage');assert.equal(b.run('writable'),true);
 await a.click('confirmOk');assert.equal(a.run('writable'),false);assert.equal(memory.get(key),latest);
 a.run('guard.dispose()');b.run('guard.dispose()');
});
test('Retry mit unlesbarem Spielstand behält Schreibschutz und verhindert automatisches Überschreiben',async()=>{
 const ui=await boot();await ui.click('start');
 ui.memory.set(key,'{"broken":true}');const raw=ui.memory.get(key);
 assert.equal(await ui.click('retryStorage'),false);
 assert.equal(ui.run('writable'),false);assert.equal(ui.run('guard.owns(sim.state.mode)'),false);
 ui.click('starter');ui.click('save');
 assert.equal(ui.memory.get(key),raw);assert.equal(ui.run('speed'),0);
 ui.run('guard.dispose()');
});
